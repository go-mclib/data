   static void summarize(final List<Packet> packets) {
      final Map<String, Long> byStatus = packets.stream().collect(Collectors.groupingBy(p -> p.status, Collectors.counting()));
      final Map<String, Long> byCodec = packets.stream().collect(Collectors.groupingBy(p -> p.codec, Collectors.counting()));
      final Set<String> raws = new TreeSet<>();
      for (final Packet p : packets) for (final Field f : p.fields) if (f.type.contains("raw:")) raws.add(f.type);
      for (final TypeDef t : TYPE_DEFS.values()) for (final Field f : t.fields) if (f.type.contains("raw:")) raws.add(f.type);
      System.err.println("packets: " + packets.size() + "  status=" + byStatus + "  codec=" + byCodec);
      System.err.println("sub-types resolved: " + TYPE_DEFS.size());
      System.err.println("distinct raw tokens (" + raws.size() + "): " + raws);
   }
