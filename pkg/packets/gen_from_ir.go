//go:build ignore

// Stage 2 of packet-binding generation: read the wire-field IR produced by
// packetdump (packets_ir.json) and emit Go structs + Read/Write into the pgen
// package. Only packets whose every field resolves to a known ns.* type are
// generated; the rest are listed as skipped (with the offending token) so the
// gap is explicit. IDs/State/Bound are intentionally left to the existing
// generate.go boilerplate pass.
//
// usage: go run gen_from_ir.go
package main

import (
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strings"
)

type irField struct {
	Name string `json:"name"`
	Type string `json:"type"`
}
type irType struct {
	Codec  string    `json:"codec"`
	Fields []irField `json:"fields"`
}
type irPacket struct {
	Clazz, Name, State, Bound, Codec, Status string
	Fields                                   []irField
}
type irDoc struct {
	Packets []irPacket        `json:"packets"`
	Types   map[string]irType `json:"types"`
}

const (
	irPath  = "../data/generate/packets_ir.json"
	outPath = "pgen/packets_gen.go"
)

// scalar wire tokens -> Go type + buffer read/write methods.
type scalar struct{ goType, readM, readArg, writeM string }

var scalars = map[string]scalar{
	"varint":        {"ns.VarInt", "ReadVarInt", "", "WriteVarInt"},
	"varlong":       {"ns.VarLong", "ReadVarLong", "", "WriteVarLong"},
	"bool":          {"ns.Boolean", "ReadBool", "", "WriteBool"},
	"i8":            {"ns.Int8", "ReadInt8", "", "WriteInt8"},
	"u8":            {"ns.Uint8", "ReadUint8", "", "WriteUint8"},
	"i16":           {"ns.Int16", "ReadInt16", "", "WriteInt16"},
	"u16":           {"ns.Uint16", "ReadUint16", "", "WriteUint16"},
	"i32":           {"ns.Int32", "ReadInt32", "", "WriteInt32"},
	"i64":           {"ns.Int64", "ReadInt64", "", "WriteInt64"},
	"f32":           {"ns.Float32", "ReadFloat32", "", "WriteFloat32"},
	"f64":           {"ns.Float64", "ReadFloat64", "", "WriteFloat64"},
	"string":        {"ns.String", "ReadString", "32767", "WriteString"},
	"bytes":         {"ns.ByteArray", "ReadByteArray", "2097152", "WriteByteArray"},
	"uuid":          {"ns.UUID", "ReadUUID", "", "WriteUUID"},
	"identifier":    {"ns.Identifier", "ReadIdentifier", "", "WriteIdentifier"},
	"position":      {"ns.Position", "ReadPosition", "", "WritePosition"},
	"globalpos":     {"ns.GlobalPos", "ReadGlobalPos", "", "WriteGlobalPos"},
	"angle":         {"ns.Angle", "ReadAngle", "", "WriteAngle"},
	"textcomponent": {"ns.TextComponent", "ReadTextComponent", "", "WriteTextComponent"},
	"json":          {"ns.TextComponent", "ReadJsonTextComponent", "", "WriteJsonTextComponent"},
	"hashedslot":    {"ns.HashedSlot", "ReadHashedSlot", "", "WriteHashedSlot"},
	"lpvec3":        {"ns.LpVec3", "ReadLpVec3", "", "WriteLpVec3"},
	"vec3d":         {"ns.LpVec3", "ReadLpVec3", "", "WriteLpVec3"}, // best-effort
	"containerid":   {"ns.VarInt", "ReadVarInt", "", "WriteVarInt"},
	"instant":       {"ns.Int64", "ReadInt64", "", "WriteInt64"},
	"optvarint":     {"ns.VarInt", "ReadVarInt", "", "WriteVarInt"}, // wire = 1 varint
	"chunkpos":      {"ns.Int64", "ReadInt64", "", "WriteInt64"},    // packed long
	"mobeffect":     {"ns.VarInt", "ReadVarInt", "", "WriteVarInt"}, // Holder registry id
	"damagetype":    {"ns.VarInt", "ReadVarInt", "", "WriteVarInt"}, // Holder registry id
}

// external sub-structs that map to an existing ns.* type with a uniform
// Decode/Encode interface. Keyed by the IR token's simple name (raw:/ref:
// prefix stripped). The generated field calls p.F.Decode(buf)/Encode(buf).
var aliases = map[string]string{
	"gameprofile":                      "ns.GameProfile",
	"ClientboundLevelChunkPacketData":  "ns.ChunkData",
	"ClientboundLightUpdatePacketData": "ns.LightData",
	"IDSet":                            "ns.IDSet",
	"ResolvableProfile":                "ns.ResolvableProfile",
	"ProfileProperty":                  "ns.ProfileProperty",
	"BlockEntity":                      "ns.BlockEntity",
}

func aliasOf(t string) string {
	name := strings.TrimPrefix(strings.TrimPrefix(t, "raw:"), "ref:")
	return aliases[name]
}

func main() {
	raw, err := os.ReadFile(irPath)
	must(err)
	var doc irDoc
	must(json.Unmarshal(raw, &doc))

	r := &resolver{types: doc.Types, memo: map[string]bool{}}

	// gather generatable sub-types referenced by generatable packets
	usedTypes := map[string]bool{}
	var gen, skip []irPacket
	for _, p := range doc.Packets {
		if r.fieldsOK(p.Fields, map[string]bool{}) {
			gen = append(gen, p)
			for _, f := range p.Fields {
				collectRefs(f.Type, doc.Types, usedTypes)
			}
		} else {
			skip = append(skip, p)
		}
	}

	var body strings.Builder
	// sub-types first (deterministic order)
	for _, name := range sortedKeys(usedTypes) {
		emitStruct(&body, name, doc.Types[name].Fields)
	}
	// packets
	sort.Slice(gen, func(i, j int) bool { return structName(gen[i]) < structName(gen[j]) })
	for _, p := range gen {
		emitStruct(&body, structName(p), p.Fields)
	}

	var b strings.Builder
	b.WriteString("// Code generated by gen_from_ir.go from packets_ir.json; DO NOT EDIT.\n\n")
	b.WriteString("package pgen\n\n")
	bodyStr := body.String()
	b.WriteString("import (\n")
	if strings.Contains(bodyStr, "items.Decoder()") {
		b.WriteString("\t\"github.com/go-mclib/data/pkg/data/items\"\n")
	}
	if strings.Contains(bodyStr, "nbt.") {
		b.WriteString("\t\"github.com/go-mclib/nbt\"\n")
	}
	b.WriteString("\tns \"github.com/go-mclib/protocol/java_protocol/net_structures\"\n)\n\n")
	b.WriteString(bodyStr)

	src, ferr := format.Source([]byte(b.String()))
	if ferr != nil {
		os.WriteFile(outPath, []byte(b.String()), 0644) // write unformatted for debugging
		fmt.Fprintln(os.Stderr, "gofmt failed (wrote raw):", ferr)
		os.Exit(1)
	}
	must(os.MkdirAll("pgen", 0755))
	must(os.WriteFile(outPath, src, 0644))

	fmt.Printf("generated %d packets + %d sub-types -> %s\n", len(gen), len(usedTypes), outPath)
	fmt.Printf("skipped %d packets (unresolved field):\n", len(skip))
	for _, p := range skip {
		fmt.Printf("  %-40s %s\n", p.Clazz, firstUnresolved(p.Fields, doc.Types))
	}
}

// ---- resolvability ----

type resolver struct {
	types map[string]irType
	memo  map[string]bool
}

func (r *resolver) fieldsOK(fields []irField, seen map[string]bool) bool {
	for _, f := range fields {
		if !r.tokenOK(f.Type, seen) {
			return false
		}
	}
	return true
}

func (r *resolver) tokenOK(t string, seen map[string]bool) bool {
	switch {
	case t == "nbt" || t == "slot":
		return true
	case strings.HasPrefix(t, "enum:"):
		return true
	case scalarOK(t):
		return true
	case aliasOf(t) != "":
		return true
	case strings.HasPrefix(t, "list<") || strings.HasPrefix(t, "optional<"):
		return r.tokenOK(inner(t), seen)
	case strings.HasPrefix(t, "ref:"):
		name := t[len("ref:"):]
		if seen[name] {
			return true // cycle: assume ok
		}
		td, ok := r.types[name]
		if !ok {
			return false
		}
		seen[name] = true
		return r.fieldsOK(td.Fields, seen)
	default:
		return false // raw:, map<>, unknown
	}
}

func scalarOK(t string) bool { _, ok := scalars[t]; return ok }

// ---- code emission ----

func emitStruct(b *strings.Builder, name string, fields []irField) {
	names := uniqueFieldNames(fields)

	fmt.Fprintf(b, "type %s struct {\n", name)
	for i, f := range fields {
		fmt.Fprintf(b, "\t%s %s\n", names[i], goType(f.Type))
	}
	b.WriteString("}\n\n")

	fmt.Fprintf(b, "func (p *%s) Read(buf *ns.PacketBuffer) error {\n\tvar err error\n\t_ = err\n", name)
	for i, f := range fields {
		b.WriteString(readStmt("p."+names[i], f.Type))
	}
	b.WriteString("\treturn nil\n}\n\n")

	fmt.Fprintf(b, "func (p *%s) Write(buf *ns.PacketBuffer) error {\n\tvar err error\n\t_ = err\n", name)
	for i, f := range fields {
		b.WriteString(writeStmt("p."+names[i], f.Type))
	}
	b.WriteString("\treturn nil\n}\n\n")
}

// exported Go field names, deduped within the struct
func uniqueFieldNames(fields []irField) []string {
	seen := map[string]int{}
	out := make([]string, len(fields))
	for i, f := range fields {
		n := goField(f.Name)
		if seen[n] > 0 {
			n = fmt.Sprintf("%s%d", n, seen[n]+1)
		}
		seen[goField(f.Name)]++
		out[i] = n
	}
	return out
}

func goType(t string) string {
	switch {
	case t == "nbt":
		return "nbt.Tag"
	case t == "slot":
		return "ns.Slot"
	case strings.HasPrefix(t, "enum:"):
		return "ns.VarInt"
	case aliasOf(t) != "":
		return aliasOf(t)
	case strings.HasPrefix(t, "list<"):
		return "ns.PrefixedArray[" + goType(inner(t)) + "]"
	case strings.HasPrefix(t, "optional<"):
		return "ns.PrefixedOptional[" + goType(inner(t)) + "]"
	case strings.HasPrefix(t, "ref:"):
		return pascal(t[len("ref:"):])
	default:
		return scalars[t].goType
	}
}

func readStmt(v, t string) string {
	switch {
	case t == "nbt":
		return fmt.Sprintf("\t{\n\t\tnr := nbt.NewReaderFrom(buf.Reader())\n\t\tif %s, _, err = nr.ReadTag(true); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", v)
	case t == "slot":
		return fmt.Sprintf("\tif %s, err = buf.ReadSlot(items.Decoder()); err != nil {\n\t\treturn err\n\t}\n", v)
	case strings.HasPrefix(t, "enum:"):
		return readStmt(v, "varint")
	case aliasOf(t) != "":
		return fmt.Sprintf("\tif err = %s.Decode(buf); err != nil {\n\t\treturn err\n\t}\n", v)
	case scalarOK(t):
		s := scalars[t]
		return fmt.Sprintf("\tif %s, err = buf.%s(%s); err != nil {\n\t\treturn err\n\t}\n", v, s.readM, s.readArg)
	case strings.HasPrefix(t, "list<"), strings.HasPrefix(t, "optional<"):
		ig := goType(inner(t))
		return fmt.Sprintf("\tif err = %s.DecodeWith(buf, func(b *ns.PacketBuffer) (%s, error) {\n%s\t}); err != nil {\n\t\treturn err\n\t}\n", v, ig, elemReader(inner(t)))
	case strings.HasPrefix(t, "ref:"):
		return fmt.Sprintf("\tif err = %s.Read(buf); err != nil {\n\t\treturn err\n\t}\n", v)
	}
	return "\t// unsupported\n"
}

func writeStmt(v, t string) string {
	switch {
	case t == "nbt":
		return fmt.Sprintf("\t{\n\t\td, e := nbt.EncodeNetwork(%s)\n\t\tif e != nil {\n\t\t\treturn e\n\t\t}\n\t\tif _, err = buf.Write(d); err != nil {\n\t\t\treturn err\n\t\t}\n\t}\n", v)
	case t == "slot":
		return fmt.Sprintf("\tif err = buf.WriteSlot(%s); err != nil {\n\t\treturn err\n\t}\n", v)
	case strings.HasPrefix(t, "enum:"):
		return writeStmt(v, "varint")
	case aliasOf(t) != "":
		return fmt.Sprintf("\tif err = %s.Encode(buf); err != nil {\n\t\treturn err\n\t}\n", v)
	case scalarOK(t):
		s := scalars[t]
		return fmt.Sprintf("\tif err = buf.%s(%s); err != nil {\n\t\treturn err\n\t}\n", s.writeM, v)
	case strings.HasPrefix(t, "list<"), strings.HasPrefix(t, "optional<"):
		ig := goType(inner(t))
		return fmt.Sprintf("\tif err = %s.EncodeWith(buf, func(b *ns.PacketBuffer, v %s) error {\n%s\t}); err != nil {\n\t\treturn err\n\t}\n", v, ig, elemWriter(inner(t)))
	case strings.HasPrefix(t, "ref:"):
		return fmt.Sprintf("\tif err = %s.Write(buf); err != nil {\n\t\treturn err\n\t}\n", v)
	}
	return "\t// unsupported\n"
}

// element reader/writer bodies for list/optional inner tokens
func elemReader(t string) string {
	if t == "slot" {
		return "\t\treturn b.ReadSlot(items.Decoder())\n"
	}
	if aliasOf(t) != "" {
		return "\t\tvar v " + aliasOf(t) + "\n\t\te := v.Decode(b)\n\t\treturn v, e\n"
	}
	if strings.HasPrefix(t, "ref:") {
		return fmt.Sprintf("\t\tvar v %s\n\t\te := v.Read(b)\n\t\treturn v, e\n", pascal(t[len("ref:"):]))
	}
	if strings.HasPrefix(t, "enum:") {
		t = "varint"
	}
	s := scalars[t]
	return fmt.Sprintf("\t\treturn b.%s(%s)\n", s.readM, s.readArg)
}

func elemWriter(t string) string {
	if t == "slot" {
		return "\t\treturn b.WriteSlot(v)\n"
	}
	if aliasOf(t) != "" {
		return "\t\treturn v.Encode(b)\n"
	}
	if strings.HasPrefix(t, "ref:") {
		return "\t\treturn v.Write(b)\n"
	}
	if strings.HasPrefix(t, "enum:") {
		t = "varint"
	}
	s := scalars[t]
	return fmt.Sprintf("\t\treturn b.%s(v)\n", s.writeM)
}

// ---- helpers ----

func collectRefs(t string, types map[string]irType, out map[string]bool) {
	switch {
	case strings.HasPrefix(t, "list<"), strings.HasPrefix(t, "optional<"):
		collectRefs(inner(t), types, out)
	case strings.HasPrefix(t, "ref:"):
		name := t[len("ref:"):]
		if out[name] || aliasOf(t) != "" { // aliased -> use the ns.* type, don't generate
			return
		}
		out[name] = true
		for _, f := range types[name].Fields {
			collectRefs(f.Type, types, out)
		}
	}
}

func firstUnresolved(fields []irField, types map[string]irType) string {
	r := &resolver{types: types, memo: map[string]bool{}}
	for _, f := range fields {
		if !r.tokenOK(f.Type, map[string]bool{}) {
			return f.Name + ":" + f.Type
		}
	}
	return "?"
}

func structName(p irPacket) string { return p.Bound + pascal(p.Name) }

func inner(t string) string {
	i := strings.IndexByte(t, '<')
	return t[i+1 : len(t)-1]
}

func goField(name string) string {
	p := pascal(name)
	if p == "" {
		p = "Field"
	}
	return p
}

func pascal(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '.' || r == '-' })
	var b strings.Builder
	for _, p := range parts {
		if p == "" {
			continue
		}
		b.WriteString(strings.ToUpper(p[:1]) + p[1:])
	}
	return b.String()
}

func sortedKeys(m map[string]bool) []string {
	var k []string
	for x := range m {
		k = append(k, x)
	}
	sort.Strings(k)
	return k
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}
