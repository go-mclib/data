//go:build ignore

// generator for packet methods (ID, State, Bound) and the packet registry.
// scans existing packet source files for struct declarations and matches them
// to generated packet ID constants, then produces packets_gen.go and registry_gen.go.
//
// usage: go run generate.go

package main

import (
	"cmp"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// phase/bound info derived from file names
type fileInfo struct {
	state string // "Handshake", "Status", "Login", "Configuration", "Play"
	bound string // "C2S", "S2C"
}

// packet struct info
type packetInfo struct {
	structName string
	idConst    string
	state      string
	bound      string
}

// file name prefix → state/bound mapping
var fileMapping = map[string]fileInfo{
	"c2s_handshaking":   {"Handshake", "C2S"},
	"c2s_status":        {"Status", "C2S"},
	"c2s_login":         {"Login", "C2S"},
	"c2s_configuration": {"Configuration", "C2S"},
	"c2s_play":          {"Play", "C2S"},
	"s2c_status":        {"Status", "S2C"},
	"s2c_login":         {"Login", "S2C"},
	"s2c_configuration": {"Configuration", "S2C"},
	"s2c_play":          {"Play", "S2C"},
}

// special cases where struct name doesn't match the ID constant convention
var idOverrides = map[string]string{
	"S2CLoginDisconnectLogin": "S2CLoginDisconnectID",
}

func main() {
	dir := "."
	if len(os.Args) > 1 {
		dir = os.Args[1]
	}

	packets := scanPacketStructs(dir)

	generatePacketMethods(packets, filepath.Join(dir, "packets_gen.go"))
	generateRegistry(packets, filepath.Join(dir, "registry_gen.go"))
}

// scanPacketStructs finds all packet struct types in the source files.
func scanPacketStructs(dir string) []packetInfo {
	var packets []packetInfo

	fset := token.NewFileSet()

	for filePrefix, info := range fileMapping {
		filename := filePrefix + ".go"
		path := filepath.Join(dir, filename)

		if _, err := os.Stat(path); os.IsNotExist(err) {
			continue
		}

		file, err := parser.ParseFile(fset, path, nil, 0)
		if err != nil {
			fmt.Fprintf(os.Stderr, "error: could not parse %s: %v\n", path, err)
			os.Exit(1)
		}

		for _, decl := range file.Decls {
			genDecl, ok := decl.(*ast.GenDecl)
			if !ok || genDecl.Tok != token.TYPE {
				continue
			}
			for _, spec := range genDecl.Specs {
				typeSpec, ok := spec.(*ast.TypeSpec)
				if !ok {
					continue
				}
				// only struct types
				if _, ok := typeSpec.Type.(*ast.StructType); !ok {
					continue
				}

				name := typeSpec.Name.Name
				// skip helper structs (not starting with C2S or S2C)
				if !strings.HasPrefix(name, "C2S") && !strings.HasPrefix(name, "S2C") {
					continue
				}

				idConst := deriveIDConst(name)
				packets = append(packets, packetInfo{
					structName: name,
					idConst:    idConst,
					state:      info.state,
					bound:      info.bound,
				})
			}
		}
	}

	// sort for deterministic output
	slices.SortFunc(packets, func(a, b packetInfo) int {
		return cmp.Or(cmp.Compare(a.state, b.state), cmp.Compare(a.bound, b.bound), cmp.Compare(a.structName, b.structName))
	})

	return packets
}

func deriveIDConst(structName string) string {
	if override, ok := idOverrides[structName]; ok {
		return override
	}
	return structName + "ID"
}

func generatePacketMethods(packets []packetInfo, outPath string) {
	var sb strings.Builder
	sb.WriteString(`// Code generated by generate.go; DO NOT EDIT.

package packets

import (
	"github.com/go-mclib/data/packetids"
	jp "github.com/go-mclib/protocol/javaproto"
	ns "github.com/go-mclib/protocol/javaproto/wire"
)

`)

	for _, p := range packets {
		fmt.Fprintf(&sb, "func (p *%s) ID() ns.VarInt   { return ns.VarInt(packetids.%s) }\n", p.structName, p.idConst)
		fmt.Fprintf(&sb, "func (p *%s) State() jp.State { return jp.State%s }\n", p.structName, p.state)
		fmt.Fprintf(&sb, "func (p *%s) Bound() jp.Bound { return jp.%s }\n\n", p.structName, p.bound)
	}

	writeFile(outPath, sb.String())
}

func generateRegistry(packets []packetInfo, outPath string) {
	// packets are sorted by state, bound, struct name; order entries by ID
	// constant within each state+bound for stable, readable output
	entries := slices.Clone(packets)
	slices.SortStableFunc(entries, func(a, b packetInfo) int {
		return cmp.Or(cmp.Compare(a.state, b.state), cmp.Compare(a.bound, b.bound), cmp.Compare(a.idConst, b.idConst))
	})

	var sb strings.Builder
	sb.WriteString(`// Code generated by generate.go; DO NOT EDIT.

package packets

import (
	"github.com/go-mclib/data/packetids"
	jp "github.com/go-mclib/protocol/javaproto"
	ns "github.com/go-mclib/protocol/javaproto/wire"
)

type packetKey struct {
	state jp.State
	bound jp.Bound
	id    ns.VarInt
}

var packetFactories = map[packetKey]func() jp.Packet{
`)

	for _, e := range entries {
		fmt.Fprintf(&sb, "\t{jp.State%s, jp.%s, packetids.%s}: func() jp.Packet { return &%s{} },\n", e.state, e.bound, e.idConst, e.structName)
	}

	sb.WriteString(`}

// NewPacket returns a new, empty packet for the given state, direction and ID,
// or false if no such packet exists.
func NewPacket(state jp.State, bound jp.Bound, id ns.VarInt) (jp.Packet, bool) {
	factory, ok := packetFactories[packetKey{state, bound, id}]
	if !ok {
		return nil, false
	}
	return factory(), true
}
`)

	writeFile(outPath, sb.String())
}

func writeFile(path, content string) {
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "error writing %s: %v\n", path, err)
		os.Exit(1)
	}
	fmt.Printf("wrote %s\n", path)
}
